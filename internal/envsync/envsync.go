// Package envsync generates and synchronizes .env.example files from an
// envguard schema. It compares the existing .env.example (if any) against
// the current schema to report additions, removals, and unchanged entries.
package envsync

import (
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/RINKESH2497/envguard/internal/schema"
)

// Options controls how the .env.example file is generated and where it is written.
type Options struct {
	// SchemaPath is the path to the envguard.yaml schema file.
	SchemaPath string

	// OutputPath is the destination path for the generated .env.example file.
	// Defaults to ".env.example" when empty.
	OutputPath string

	// IncludeDescriptions adds a comment line with the variable description
	// above each entry. Defaults to true.
	IncludeDescriptions bool

	// IncludeTypes adds type and required/optional annotations to the
	// description comment. Defaults to true.
	IncludeTypes bool

	// GroupByRequired separates required variables from optional ones with a
	// section header comment.
	GroupByRequired bool
}

// SyncResult summarises the changes produced by a Sync operation.
type SyncResult struct {
	// Created is true when the output file did not previously exist.
	Created bool

	// Updated is true when the output file existed and its content changed.
	Updated bool

	// Added lists variable names that are new in this sync.
	Added []string

	// Removed lists variable names that were present before but are no longer
	// in the schema.
	Removed []string

	// Unchanged is the count of variables that remained the same.
	Unchanged int
}

// defaults fills zero-value fields in Options with sensible defaults.
func (o *Options) defaults() {
	if o.OutputPath == "" {
		o.OutputPath = ".env.example"
	}
	// IncludeDescriptions and IncludeTypes default to true. Because Go
	// zero-values are false we use a constructor-style approach: callers
	// that want the defaults should use NewOptions(). For Sync/Generate
	// called directly we treat unset (false) as "not explicitly disabled"
	// only when the caller is expected to set them. In practice the CLI
	// layer always sets these explicitly, so we leave them as-is here.
}

// NewOptions returns an Options value with all defaults pre-filled.
func NewOptions() Options {
	return Options{
		OutputPath:          ".env.example",
		IncludeDescriptions: true,
		IncludeTypes:        true,
		GroupByRequired:     false,
	}
}

// Sync loads the schema, generates a new .env.example, detects changes
// against any existing file, writes the result, and returns a SyncResult.
func Sync(opts Options) (*SyncResult, error) {
	opts.defaults()

	s, err := schema.LoadFile(opts.SchemaPath)
	if err != nil {
		return nil, fmt.Errorf("envsync: loading schema: %w", err)
	}

	content, err := Generate(s, opts)
	if err != nil {
		return nil, fmt.Errorf("envsync: generating content: %w", err)
	}

	result := &SyncResult{}

	// Determine what changed compared to the existing file.
	existing, readErr := os.ReadFile(opts.OutputPath)
	if readErr != nil {
		if !os.IsNotExist(readErr) {
			return nil, fmt.Errorf("envsync: reading existing file: %w", readErr)
		}
		result.Created = true
	}

	if !result.Created {
		result.Added, result.Removed, result.Unchanged = diff(existing, content)
		result.Updated = len(result.Added) > 0 || len(result.Removed) > 0
		if !result.Updated && !bytes.Equal(existing, content) {
			// Content changed (e.g. descriptions) but same set of vars.
			result.Updated = true
		}
	} else {
		// Everything is new.
		for _, v := range s.OrderedVars() {
			result.Added = append(result.Added, v.Name)
		}
	}

	if err := os.WriteFile(opts.OutputPath, content, 0644); err != nil {
		return nil, fmt.Errorf("envsync: writing file: %w", err)
	}

	return result, nil
}

// Generate produces the .env.example content as bytes without writing to disk.
func Generate(s *schema.Schema, opts Options) ([]byte, error) {
	if s == nil {
		return nil, fmt.Errorf("envsync: schema must not be nil")
	}
	opts.defaults()

	var buf bytes.Buffer

	// Header
	buf.WriteString("# Generated by envguard — do not edit manually\n")
	buf.WriteString("#\n")
	buf.WriteString(fmt.Sprintf("# Source schema: %s\n", opts.SchemaPath))
	buf.WriteString("\n")

	vars := s.OrderedVars()
	if opts.GroupByRequired {
		vars = groupByRequired(vars)
	}

	wroteRequiredHeader := false
	wroteOptionalHeader := false

	for i, v := range vars {
		// Section headers when grouping.
		if opts.GroupByRequired {
			if v.Required && !wroteRequiredHeader {
				buf.WriteString("# ──────────────────────────────────────\n")
				buf.WriteString("# Required variables\n")
				buf.WriteString("# ──────────────────────────────────────\n\n")
				wroteRequiredHeader = true
			}
			if !v.Required && !wroteOptionalHeader {
				if wroteRequiredHeader {
					buf.WriteString("\n")
				}
				buf.WriteString("# ──────────────────────────────────────\n")
				buf.WriteString("# Optional variables\n")
				buf.WriteString("# ──────────────────────────────────────\n\n")
				wroteOptionalHeader = true
			}
		}

		if opts.IncludeDescriptions || opts.IncludeTypes {
			comment := buildComment(v, opts)
			buf.WriteString(comment)
		}

		value := exampleValue(v)
		buf.WriteString(fmt.Sprintf("%s=%s\n", v.Name, value))

		// Blank line between entries (except after the last one).
		if i < len(vars)-1 {
			buf.WriteString("\n")
		}
	}

	return buf.Bytes(), nil
}

// buildComment formats the descriptive comment line(s) for a variable.
func buildComment(v schema.Var, opts Options) string {
	var meta []string
	if opts.IncludeTypes {
		if v.Type != "" {
			meta = append(meta, fmt.Sprintf("Type: %s", v.Type))
		}
		if v.Required {
			meta = append(meta, "Required")
		} else {
			meta = append(meta, "Optional")
		}
	}

	metaStr := ""
	if len(meta) > 0 {
		metaStr = "(" + strings.Join(meta, ", ") + ")"
	}

	if opts.IncludeDescriptions && v.Description != "" {
		if metaStr != "" {
			return fmt.Sprintf("# %s %s\n", v.Description, metaStr)
		}
		return fmt.Sprintf("# %s\n", v.Description)
	}

	if metaStr != "" {
		return fmt.Sprintf("# %s\n", metaStr)
	}

	return ""
}

// exampleValue returns the placeholder value for a variable in the .env.example.
func exampleValue(v schema.Var) string {
	if v.Secret {
		return "<secret>"
	}
	if v.Default != "" {
		return v.Default
	}
	if v.Example != "" {
		return v.Example
	}
	return ""
}

// groupByRequired returns a copy of vars sorted with required first, then
// optional. Within each group the original order is preserved.
func groupByRequired(vars []schema.Var) []schema.Var {
	sorted := make([]schema.Var, len(vars))
	copy(sorted, vars)
	sort.SliceStable(sorted, func(i, j int) bool {
		if sorted[i].Required == sorted[j].Required {
			return false // preserve original order within group
		}
		return sorted[i].Required // required comes first
	})
	return sorted
}

// diff compares old and new .env.example content to determine which variable
// names were added, removed, or unchanged.
func diff(old, new []byte) (added, removed []string, unchanged int) {
	oldVars := parseVarNames(old)
	newVars := parseVarNames(new)

	oldSet := make(map[string]bool, len(oldVars))
	for _, name := range oldVars {
		oldSet[name] = true
	}

	newSet := make(map[string]bool, len(newVars))
	for _, name := range newVars {
		newSet[name] = true
	}

	for _, name := range newVars {
		if !oldSet[name] {
			added = append(added, name)
		} else {
			unchanged++
		}
	}

	for _, name := range oldVars {
		if !newSet[name] {
			removed = append(removed, name)
		}
	}

	return added, removed, unchanged
}

// parseVarNames extracts environment variable names from .env.example content.
// It looks for lines matching NAME=... that are not comments.
func parseVarNames(data []byte) []string {
	var names []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if idx := strings.IndexByte(line, '='); idx > 0 {
			name := strings.TrimSpace(line[:idx])
			if isValidEnvName(name) {
				names = append(names, name)
			}
		}
	}
	return names
}

// isValidEnvName checks that a string looks like a valid environment variable
// name (letters, digits, and underscores, not starting with a digit).
func isValidEnvName(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		if c >= '0' && c <= '9' {
			if i == 0 {
				return false
			}
			continue
		}
		if (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_' {
			continue
		}
		return false
	}
	return true
}
